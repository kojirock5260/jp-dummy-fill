/**
 * seed の初期値。ページを開いた時刻から決める。
 *
 * 固定の seed 0 を既定にしていたが、会員登録のテストで同じメールアドレスが二度目に
 * 弾かれる。毎回別の人が出れば衝突しない。乱数ではなく時刻にしたのは、番号を控えて
 * おけば同じ人を呼び戻せるから。「ランダムに見えるが、番号で決まっている」。
 *
 * 分刻みなので、同じ分に開いた 2 つのタブは同じ人になる。同じテストの続きなら困らない。
 */

/** 番号の起点。この日時を 0 とする。番号を短く保つため、UNIX 時間そのものは使わない。 */
export const SEED_EPOCH = Date.UTC(2026, 0, 1);

/**
 * その時刻に開いたページの seed。起点から数えた分の数。
 *
 * @param now 開いた時刻
 * @returns 0 以上の整数。起点より前なら 0
 */
export function seedAt(now: Date): number {
  return Math.max(0, Math.floor((now.getTime() - SEED_EPOCH) / 60_000));
}

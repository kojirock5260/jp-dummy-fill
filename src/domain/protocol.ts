/**
 * Service Worker とコンテンツスクリプトの間で交わすメッセージ。
 *
 * 双方が同じ型を見るように 1 箇所へ集めてある。
 * 送る側と受ける側で文字列を書き間違えても、ここを経由していれば型で気づける。
 *
 * 右クリックメニューの 3 項目と 1 対 1。
 *
 * - `fill`  … 今の人物で、空いている欄を埋める。人物はページを開いた時刻で決まる（使い捨て）
 * - `place` … 住所を選ぶパレットを開く。選ぶと人物はそのまま住所の欄だけを上書きする
 * - `pick`  … 1 つの欄に入れる欄種を選ぶパレットを開く
 *
 * 「固定データで入力」は置かない。常に同じ人物が要る場面は「同じアカウントに何度も入る」
 * くらいで、それはメールアドレス末尾の番号をパレットに打てば足りる。「別人で入力」も
 * 無い。使い捨ての人物はページを開き直せば変わる。
 *
 * seed と今の住所を持つのはコンテンツスクリプト側。Service Worker は種類だけを伝える。
 */
export type Message =
  /** ページの空いている欄を全部埋める。 */
  | { type: "fill" }
  /**
   * 住所を選ぶパレットを開く。並ぶ場所は `domain/places.ts`。
   *
   * 「遠隔地」「離島」をチェック式の設定にしなかったのは、状態を置く場所が無いからでもあり
   * （Service Worker は眠ると変数が消え、`storage` は使わない）、チェックを付けても埋まった
   * ページでは何も起きないからでもある。選べば必ず住所が変わる動作のほうが迷わない。
   */
  | { type: "place" }
  /**
   * 右クリックした（または今フォーカスのある）1 つの欄のそばに、欄種を選ぶパレットを開く。
   *
   * 自動の判定が外した欄を、その場で直すための入口。どの欄かは送らない。
   * Chrome の右クリックメニューは押された要素を教えてくれないので、ページ側が
   * 右クリックの時点で覚えておく。`via` はどちらから来たか。ショートカットで来た
   * ときは、右クリックの記憶よりフォーカスのある欄を信じる。
   */
  | { type: "pick"; via: "menu" | "key" };

/**
 * コンテンツスクリプトからの返事。
 *
 * `filled` は実際に値を書いた欄の数。バッジに出す。0 でも成功として返す。
 * 空いている欄が無かったのと、ページに入れられなかったのは別の事態なので、
 * 後者だけを `ok: false` にする。誰が記入したかは返さない。人物の番号はメールアドレスの
 * 末尾に見えていて、アイコンに載せても見に行く人がいない。
 *
 * `opened` はパレットを開いたとき。人が選び終わるまで待たないので数は無い。
 * 選んだあとの結果は {@link Report} でコンテンツスクリプトから届く。
 *
 * `noTarget` は、右クリックされた欄もフォーカスのある欄も無かったとき。
 */
export type Reply =
  | { ok: true; filled: number }
  | { ok: true; opened: true }
  | { ok: false; reason?: "noTarget" };

/**
 * コンテンツスクリプトから Service Worker へ、あとから届く結果。
 *
 * パレットで欄種や場所を選んだときと、番号で人物を呼び戻したとき。返事の口はもう閉じている
 * ので、こちらから送る。Service Worker はバッジに出すだけ。
 */
export type Report = { type: "report"; filled: number };
